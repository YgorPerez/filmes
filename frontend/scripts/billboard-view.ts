// Builds the Cartaz's MCP Apps view (`src/mcp-view`) into one HTML file,
// its JS and CSS inline (MCP Apps' default CSP takes inline scripts and
// styles, and nothing from another origin), and writes it where the MCP
// server serves it as `ui://filmes/cartaz.html`:
// `packages/mcp-server/src/billboard-view.gen.ts`. The file is committed, so
// the server and whoever bundles it (the app's Nitro build) need no build
// step of their own; `billboard-view.test.ts` fails when it drifts from the
// component.
//
//   node scripts/billboard-view.ts

import { writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import tailwindcss from '@tailwindcss/vite'
import viteReact from '@vitejs/plugin-react'
import { build, type Rolldown } from 'vite'

const VIEW = resolve(import.meta.dirname, '../src/mcp-view')

export const GENERATED = resolve(
  import.meta.dirname,
  '../../packages/mcp-server/src/billboard-view.gen.ts',
)

/** A `</script>` or `</style>` inside the code would end the tag. */
const inlineSafe = (code: string, tag: 'script' | 'style') =>
  code.replaceAll(`</${tag}`, `<\\/${tag}`)

/** The view as one HTML document. */
export async function buildBillboardView(): Promise<string> {
  // Vite and React's plugin read production from NODE_ENV, which Vitest
  // sets to `test` (JSX in development, the packages' `development`
  // exports): the test must build the committed file.
  const environment = process.env.NODE_ENV
  process.env.NODE_ENV = 'production'
  try {
    return await buildProduction()
  } finally {
    process.env.NODE_ENV = environment
  }
}

async function buildProduction(): Promise<string> {
  const built = await build({
    configFile: false,
    root: VIEW,
    mode: 'production',
    logLevel: 'silent',
    plugins: [tailwindcss(), viteReact()],
    build: {
      write: false,
      modulePreload: false,
      cssCodeSplit: false,
      assetsInlineLimit: Number.POSITIVE_INFINITY,
      // One classic script: some WebViews (and jsdom) run no module
      // script inline.
      rollupOptions: { output: { codeSplitting: false, format: 'iife' } },
    },
  })
  const [bundle] = Array.isArray(built) ? built : [built]
  const files = (bundle as Rolldown.RolldownOutput).output
  const text = (name: string) => {
    const file = files.find((f) => f.fileName.endsWith(name))
    if (file === undefined) throw new Error(`the view's build has no ${name}`)
    return file.type === 'chunk' ? file.code : String(file.source)
  }
  if (files.length !== 3)
    throw new Error(
      `the view must build into one HTML, one JS and one CSS: ${files.map((f) => f.fileName).join(', ')}`,
    )
  // A classic script runs where it stands: after the root it renders in.
  return text('index.html')
    .replace(
      /\s*<script type="module" crossorigin src="[^"]+\.js"><\/script>/u,
      '',
    )
    .replace(
      '</body>',
      () => `<script>${inlineSafe(text('.js'), 'script')}</script>\n  </body>`,
    )
    .replace(
      /<link rel="stylesheet" crossorigin href="[^"]+\.css">/u,
      () => `<style>${inlineSafe(text('.css'), 'style')}</style>`,
    )
}

/** The module the MCP server imports. */
export const generatedModule = (html: string) =>
  '// Generated by `node frontend/scripts/billboard-view.ts` from\n' +
  '// `frontend/src/mcp-view`: the Cartaz as one HTML file. Do not edit.\n' +
  `export const BILLBOARD_VIEW_HTML = ${JSON.stringify(html)}\n`

if (import.meta.main) {
  writeFileSync(GENERATED, generatedModule(await buildBillboardView()))
  console.log(`[billboard-view] -> ${GENERATED}`)
}
