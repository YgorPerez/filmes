// The dated report of a real-database run, for `docs/oracle/` (#76 §4.6).
// It is committed, so it carries counts and anonymised ids only: no value
// from either side (evidence text, titles a Pessoa rated, Session
// contents), and no Pessoa's slug, name or alias, which a difference path
// may hold (`output.films[0].utility.<slug>`, `data/sessions/<date>-<slug>.md`).
// A last check refuses a report where one is still there.

import type { Report } from '../report.ts'
import type { RealFacts } from './run.ts'

const escape = (text: string) => text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')

/** Replaces every private token (whole words, any case) with `<pessoa>`. */
export function anonymiser(tokens: readonly string[]): {
  readonly clean: (text: string) => string
  readonly leaks: (text: string) => boolean
} {
  const sorted = [...new Set(tokens.filter((t) => t.trim() !== ''))].sort(
    (a, b) => b.length - a.length,
  )
  const pattern =
    sorted.length === 0
      ? undefined
      : new RegExp(
          `(?<![\\p{L}\\p{N}])(?:${sorted.map(escape).join('|')})(?![\\p{L}\\p{N}])`,
          'giu',
        )
  return {
    clean: (text) => (pattern ? text.replace(pattern, '<pessoa>') : text),
    leaks: (text) =>
      pattern ? new RegExp(pattern.source, 'iu').test(text) : false,
  }
}

const list = (counts: Readonly<Record<string, number>>) => {
  const entries = Object.entries(counts).sort(
    ([a, x], [b, y]) => y - x || (a < b ? -1 : 1),
  )
  return entries.length === 0
    ? 'none'
    : entries.map(([key, n]) => `${key} ×${n}`).join(', ')
}

const total = (counts: Readonly<Record<string, number>>) =>
  Object.values(counts).reduce((a, b) => a + b, 0)

export interface RealReportContext {
  readonly facts: RealFacts
  readonly report: Report
  readonly private: readonly string[]
  /** The commit the run was made on. */
  readonly commit: string
  readonly lanes: number
  readonly ranOn: string
}

/** The report in Markdown. Throws if a private token survived. */
export function formatRealReport(context: RealReportContext): string {
  const { facts, report } = context
  const { clean, leaks } = anonymiser(context.private)
  const groups = new Map<string, { count: number; steps: string[] }>()
  for (const d of report.unexplained) {
    const path = clean(d.path).replace(/\[\d+\]/g, '[*]')
    const key = `${d.check}\u0000${d.command}\u0000${path}`
    const group = groups.get(key) ?? { count: 0, steps: [] }
    group.count++
    const at = `${d.scenario} step ${d.step + 1}`
    if (group.steps.length < 3 && !group.steps.includes(at))
      group.steps.push(at)
    groups.set(key, group)
  }
  const lines = [
    `# Real-database oracle run, ${context.ranOn}`,
    '',
    'Generated by `pnpm oracle --real` (#84, #76 §4.2 item 2). Counts and anonymised step ids only: no value from either engine and no Pessoa.',
    '',
    '## Run',
    '',
    `- Commit: \`${context.commit}\``,
    `- Seed: ${facts.seed} (\`--seed ${facts.seed}\` replays the same requests on the same data)`,
    `- \`FILMES_HOJE\`: ${facts.today}`,
    `- Lanes: ${context.lanes}; wall time: ${Math.round(facts.seconds / 60)} min`,
    `- Inputs: a copy of the real database (${facts.films.toLocaleString('en-US')} films) and of the real filmes-dados (${facts.people} Pessoas, ${facts.sessionsInData} Sessions)`,
    `- Tables compared after each step: the ${facts.dataTables.length} that filmes-dados loads (${facts.dataTables.join(', ')}); the catalog tables are byte copies on both sides`,
    `- API keys: ${facts.keys.length === 0 ? 'none on this machine, so no source was reached; each side read the copy of the existing cache, and a miss gave the "sem chave" warning on both' : facts.keys.join(', ') + " (Python's seed-0 pass only; the other sides read its cache)"}`,
    `- Cache at the start: ${list(facts.cacheBefore)}; rows Python's pass added: ${list(facts.fetched)}`,
    '',
    '## Steps',
    '',
    `- Scenarios: ${report.scenarios}; steps run: ${report.steps}; steps not run (no Session opened): ${facts.stopped}`,
    `- Compared on both engines: ${total(report.compared)} (${list(report.compared)})`,
    `- Python only (not ported): ${total(report.notPorted)} (${list(report.notPorted)})`,
    `- Explained by \`decisions.yaml\`: ${total(report.explained)} (${list(report.explained)})`,
    '',
    '## Differences no decision explains',
    '',
  ]
  for (const check of ['parity', 'self-check'] as const)
    lines.push(
      `- ${check}: ${report.unexplained.filter((d) => d.check === check).length}`,
    )
  if (groups.size > 0) {
    lines.push(
      '',
      '| check | command | path | count | first steps |',
      '| --- | --- | --- | --- | --- |',
    )
    for (const [key, group] of [...groups].sort(([a], [b]) =>
      a < b ? -1 : 1,
    )) {
      const [check, command, path] = key.split('\u0000')
      lines.push(
        `| ${check} | ${command} | \`${path}\` | ${group.count} | ${group.steps.join('; ')} |`,
      )
    }
  }
  lines.push('', `## Harness errors`, '', `- ${report.errors.length}`)
  for (const { scenario } of report.errors) lines.push(`  - ${scenario}`)
  lines.push('', `**Result: ${report.ok ? 'clean' : 'FAILED'}.**`, '')
  const text = lines.join('\n')
  if (leaks(text))
    throw new Error(
      'oracle --real: the report still names a Pessoa; not written',
    )
  return text
}
