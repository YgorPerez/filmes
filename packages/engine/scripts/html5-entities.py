"""Writes `src/compat/html5-entities.ts`: the named character references of
Python's `html.unescape` (`html.entities.html5`) and its table of invalid
numeric references (`html._invalid_charrefs`, `html._invalid_codepoints`).

The Letterboxd import turns a review's HTML into text with `html.unescape`;
the port carries the tables of the Python it replaces. Run it with that
Python, from the repository root, then format:

    uv run python packages/engine/scripts/html5-entities.py && pnpm fmt
"""

import html
import json
import sys
from html.entities import html5
from pathlib import Path

OUT = Path(__file__).parent.parent / "src" / "compat" / "html5-entities.ts"


def main():
    names = {name: value for name, value in sorted(html5.items())}
    invalid_refs = {str(k): v for k, v in sorted(html._invalid_charrefs.items())}
    invalid_points = sorted(html._invalid_codepoints)
    OUT.write_text(
        "// Generated by scripts/html5-entities.py from Python "
        f"{sys.version_info.major}.{sys.version_info.minor}"
        ". Do not edit.\n\n"
        "/** `html.entities.html5`: a name (with its ';' when the name needs one) and\n"
        " * the text it stands for. */\n"
        f"export const HTML5: Readonly<Record<string, string>> = {json.dumps(names, ensure_ascii=True)}\n\n"
        "/** `html._invalid_charrefs`: numeric references the standard replaces. */\n"
        f"export const INVALID_CHARREFS: Readonly<Record<string, string>> = {json.dumps(invalid_refs, ensure_ascii=True)}\n\n"
        "/** `html._invalid_codepoints`: numeric references that vanish. */\n"
        f"export const INVALID_CODEPOINTS: readonly number[] = {json.dumps(invalid_points)}\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
