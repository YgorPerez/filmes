"""Writes `src/compat/casefold-table.ts`: Python's `str.casefold`, one code
point at a time, as runs of the same shift and the multi-character folds.

JavaScript has no full case folding (`toLowerCase` leaves `ß` alone), so
the engine carries the table of the Python it replaces. Run it with that
Python, from the repository root, then format:

    uv run python packages/engine/scripts/casefold-table.py && pnpm fmt
"""

import json
import sys
import unicodedata
from pathlib import Path

OUT = Path(__file__).parent.parent / "src" / "compat" / "casefold-table.ts"


def main():
    runs, multi = [], []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        folded = chr(cp).casefold()
        if folded == chr(cp):
            continue
        if len(folded) > 1:
            multi.append([cp, folded])
            continue
        delta = ord(folded) - cp
        last = runs[-1] if runs else None
        if last and last[3] == delta:
            step = cp - last[1]
            # A run of one takes its step (1, or 2 for upper and lower
            # alternating) from its second code point.
            if last[0] == last[1] and step in (1, 2):
                last[1], last[2] = cp, step
                continue
            if last[0] != last[1] and step == last[2]:
                last[1] = cp
                continue
        runs.append([cp, cp, 1, delta])
    lines = [
        f"// Generated by scripts/casefold-table.py from Python {sys.version.split()[0]}",
        f"// (Unicode {unicodedata.unidata_version}). Do not edit; rerun the script.",
        "",
        "/** [first, last, step, shift]: every `step`-th code point from `first` to",
        " * `last` folds to itself plus `shift`. */",
        f"export const RUNS: ReadonlyArray<readonly [number, number, number, number]> = {json.dumps(runs)}",
        "",
        "/** The code points that fold to more than one. */",
        f"export const MULTI: ReadonlyArray<readonly [number, string]> = {json.dumps(multi, ensure_ascii=False)}",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
