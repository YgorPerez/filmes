"""Writes `src/compat/log1p-table.ts`: the ints up to LIMIT whose
`math.log1p` differs from V8's `Math.log1p`, with Python's value.

The similarity (`recomendacao/parecenca.py`) weighs each MovieLens tag by
`log1p(users)`, and V8's fdlibm `log1p` differs from glibc's in the last bit
for a few ints (175 and 184 among them). Run it with the engine's Python and
a Node on PATH, from the repository root, then format:

    uv run python packages/engine/scripts/log1p-table.py && pnpm fmt
"""

import math
import struct
import subprocess
import sys
from pathlib import Path

OUT = Path(__file__).parent.parent / "src" / "compat" / "log1p-table.ts"
LIMIT = 2_000_000

NODE = f"""
const b = Buffer.alloc(8)
const out = []
for (let i = 0; i <= {LIMIT}; i++) {{ b.writeDoubleBE(Math.log1p(i)); out.push(b.toString('hex')) }}
process.stdout.write(out.join('\\n'))
"""


def main():
    js = subprocess.run(["node", "-e", NODE], capture_output=True, text=True, check=True).stdout.split("\n")
    exceptions = []
    for n in range(LIMIT + 1):
        py = math.log1p(n)
        if struct.pack(">d", py).hex() != js[n]:
            exceptions.append(f"[{n}, {py!r}]")
    lines = [
        f"// Generated by scripts/log1p-table.py from Python {sys.version.split()[0]} and Node",
        f"// {subprocess.run(['node', '--version'], capture_output=True, text=True, check=True).stdout.strip()}. Do not edit; rerun the script.",
        "",
        "/** The ints from 0 to this one are checked against Python's `math.log1p`. */",
        f"export const LOG1P_CHECKED_UP_TO = {LIMIT}",
        "",
        "/** [n, math.log1p(n)] where V8's `Math.log1p(n)` differs. */",
        f"export const LOG1P_EXCEPTIONS: ReadonlyArray<readonly [number, number]> = [{', '.join(exceptions)}]",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
